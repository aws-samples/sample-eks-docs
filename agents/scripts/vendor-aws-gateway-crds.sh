#!/usr/bin/env bash
#
# Vendor the AWS Gateway API extension CRDs (gateway.k8s.aws: LoadBalancerConfiguration,
# TargetGroupConfiguration, ListenerRuleConfiguration) into the base chart.
#
#   ./scripts/vendor-aws-gateway-crds.sh            # the pinned tag below
#   ./scripts/vendor-aws-gateway-crds.sh v3.7.0     # another tag; update VERSIONS.md with it
#
# WHY THEY ARE IN THE BASE CHART. The base chart renders objects of these kinds when ingress is on.
# Installed by a sibling Argo CD Application, the CRDs race the base chart's sync: refreshed onto
# the commit that turns ingress on before they exist, the chart's render fails and stays failed
# until Argo CD next hard-refreshes it, and without the render guard the sync applies a failing
# LoadBalancerConfiguration and then waits forever on a later wave's health. In the same Application, at a wave before every object that uses them, Argo CD
# applies them and waits for them to be established first, in one operation.
#
# Each CRD gets: sync-wave -2; Prune=false, because a kept cluster may have its own objects of these
# kinds and pruning a CRD deletes every one of them; IgnoreExtraneous, so ingress turned off leaves
# the Application Synced; and the stack's part-of label, which teardown.sh attributes by. EKS Auto
# Mode runs the controller; these are only the schemas.
set -euo pipefail
TAG="${1:-v3.6.2}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/gitops/base/files/aws-gateway-api-crds.yaml"
URL="https://raw.githubusercontent.com/kubernetes-sigs/aws-load-balancer-controller/$TAG/config/crd/gateway/gateway-crds.yaml"
src="$(curl -sfL "$URL")" || { echo "could not fetch $URL" >&2; exit 1; }
{
  echo "# gateway.k8s.aws CRDs from kubernetes-sigs/aws-load-balancer-controller $TAG"
  echo "# (config/crd/gateway/gateway-crds.yaml). GENERATED by scripts/vendor-aws-gateway-crds.sh; do not edit."
  printf '%s\n' "$src" | awk '
    /^metadata:$/ { print; inmeta=1; next }
    inmeta && /^  annotations:$/ {
      print
      print "    argocd.argoproj.io/sync-wave: \"-2\""
      print "    argocd.argoproj.io/sync-options: Prune=false"
      print "    argocd.argoproj.io/compare-options: IgnoreExtraneous"
      next }
    inmeta && /^  name:/ {
      print
      print "  labels:"
      print "    app.kubernetes.io/part-of: eks-agents-paved-paths"
      inmeta=0; next }
    { print }'
} > "$OUT"
n="$(grep -c '^kind: CustomResourceDefinition' "$OUT")"
w="$(grep -c 'sync-wave: "-2"' "$OUT")"
[[ "$n" -eq 3 && "$w" -eq 3 ]] || { echo "expected 3 CRDs, each annotated; got $n CRDs, $w annotated" >&2; exit 1; }
echo "wrote $OUT ($n CRDs, $TAG)"
